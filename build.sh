#!/usr/bin/env bash
# ============================================================
# build.sh — keep every page fully self-contained (idempotent).
#
# Inlines assets/css/styles.css (design system) and
# assets/js/main.js (behavior) into all HTML pages, so the
# site renders completely styled and interactive anywhere:
#   • the Freebuff preview tab (serves one file at a time)
#   • double-clicking any page locally (file://)
#   • any static host (Netlify, GitHub Pages, cPanel, ...)
#
# SOURCE OF TRUTH for future edits:
#   • design   →  assets/css/styles.css
#   • behavior →  assets/js/main.js
#
# After editing either file, re-apply to all pages with:
#   bash build.sh
#
# Safe to run any number of times: it replaces the region
# between the INLINE:CSS / INLINE:JS marker comments that it
# writes on first run (and also recognizes the original
# external <link>/<script> tags for fresh checkouts).
# ============================================================
set -euo pipefail
cd "$(dirname "$0")"

PAGES="index.html about.html leadership-business.html ministry.html philanthropy.html speaking.html media.html contact.html"

export INLINE_CSS_START='<!-- INLINE:CSS:START (generated by build.sh) - edit assets/css/styles.css, then run: bash build.sh -->'
export INLINE_CSS_END='<!-- INLINE:CSS:END -->'
export INLINE_JS_START='<!-- INLINE:JS:START (generated by build.sh) - edit assets/js/main.js, then run: bash build.sh -->'
export INLINE_JS_END='<!-- INLINE:JS:END -->'

for f in $PAGES; do
  [ -f "$f" ] || { echo "skip (missing): $f"; continue; }

  perl -0777 -pi -e '
    BEGIN {
      open my $c, "<", "assets/css/styles.css" or die "cannot read assets/css/styles.css\n";
      local $/; $css = <$c>; close $c;
      open my $j, "<", "assets/js/main.js" or die "cannot read assets/js/main.js\n";
      $js = <$j>; close $j;
      $newCss = $ENV{INLINE_CSS_START} . "\n  <style>\n" . $css . "  </style>\n  " . $ENV{INLINE_CSS_END};
      $newJs  = $ENV{INLINE_JS_START} . "\n  <script>\n" . $js . "  </script>\n  " . $ENV{INLINE_JS_END};
    }

    # ---- CSS: fresh tag -> marked block -> legacy unmarked inline ----
    if    (s{<link rel="stylesheet" href="assets/css/styles\.css">}{$newCss}) { }
    elsif (s{<!-- INLINE:CSS:START.*?<!-- INLINE:CSS:END -->}{$newCss}s)      { }
    elsif (s{<!-- Design system inlined from assets/css/styles\.css.*?-->\s*<style>\n.*?[^\S\n]*</style>}{$newCss}s) { }

    # ---- JS: fresh tag -> marked block -> legacy unmarked inline ----
    if    (s{<script src="assets/js/main\.js" defer></script>}{$newJs}) { }
    elsif (s{<!-- INLINE:JS:START.*?<!-- INLINE:JS:END -->}{$newJs}s)   { }
    elsif (s{<script>\s*/\*\s*=+\s*Main site behavior.*?</script>}{$newJs}s) { }
  ' "$f"

  echo "processed: $f"
done

# ---- Verify every page actually carries fresh inline blocks ----
FAIL=0
for f in $PAGES; do
  [ -f "$f" ] || continue
  grep -q 'INLINE:CSS:START' "$f" || { echo "ERROR: fresh CSS block missing in $f"; FAIL=1; }
  grep -q 'INLINE:JS:START'  "$f" || { echo "ERROR: fresh JS block missing in $f";  FAIL=1; }
  grep -q '<link rel="stylesheet" href="assets/css/styles.css">' "$f" && { echo "ERROR: external CSS link still present in $f"; FAIL=1; }
  grep -q '<script src="assets/js/main.js"' "$f" && { echo "ERROR: external JS tag still present in $f"; FAIL=1; }
done

if [ "$FAIL" -eq 0 ]; then
  echo "OK: all pages are self-contained and carry the latest CSS/JS."
else
  echo "FAILED: see errors above."
  exit 1
fi
